export function get_tool_reference_topics() {
  return Array.from(TOPICS.keys());
}

export function agent_get_tool_reference(input = {}) {
  const topic = optional_string(input, "topic") || "tool_discovery";
  const normalized_topic = topic.trim().toLowerCase();
  const reference = TOPICS.get(normalized_topic);
  if (!reference) {
    throw new JsonRpcError(
      -32602,
      `Unknown tool reference topic: ${topic}. Valid topics: ${get_tool_reference_topics().join(", ")}`,
    );
  }

  const format = (optional_string(input, "format") || "summary").trim().toLowerCase();
  if (!["summary", "schema", "workflow"].includes(format)) {
    throw new JsonRpcError(-32602, `Unknown tool reference format: ${format}. Valid formats: summary, schema, workflow`);
  }

  if (format === "schema") {
    return {
      topic: reference.topic,
      schema: reference.schema ?? null,
      skill_references: reference.skill_references ?? [],
      valid_topics: get_tool_reference_topics(),
    };
  }

  if (format === "workflow") {
    return {
      topic: reference.topic,
      purpose: reference.purpose,
      workflow: reference.workflow ?? [],
      primary_tools: reference.primary_tools ?? [],
      tool_search_queries: reference.tool_search_queries ?? [],
      skill_references: reference.skill_references ?? [],
      valid_topics: get_tool_reference_topics(),
    };
  }

  return {
    ...reference,
    valid_topics: get_tool_reference_topics(),
  };
}
